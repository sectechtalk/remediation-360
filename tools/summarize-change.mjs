// Helper for tools/Watch-R360Summaries.ps1, the interim "Claude handoff" for Summarize now while r360 has no AI
// provider API key. The watcher (PowerShell) reads the shared mailbox with the operator's delegated Graph sign-in and
// talks to GitHub with gh; this file only does the parts that must match r360 exactly, by reusing r360's own code:
//   node tools/summarize-change.mjs prompt   stdin {number, messages: [raw Graph messages]}  ->  stdout {emails, system, prompt}
//   node tools/summarize-change.mjs comment  stdin {number, text, emails, by, truncated}      ->  stdout {body}
// No tokens pass through here, and nothing is written to disk.
import { fileURLToPath } from 'node:url';
import { toMail, changeNumber } from '../server/mailbox.mjs';
import { transcript, mdSafe, inline, summaryBlock } from '../server/requests.mjs';
import { SUMMARY_SYSTEM } from '../server/llm.mjs';

export const HANDOFF_PROVIDER = 'claude-handoff';
export const HANDOFF_MODEL = 'Claude Code';

const pt = d => `${d.toLocaleString('en-US', { timeZone: 'America/Los_Angeles', dateStyle: 'medium', timeStyle: 'short' })} PT`;

export function prepare({ number, messages }) {
  const n = Number(number);
  if (!Number.isInteger(n) || n < 1) throw new Error('number must be a positive whole number');
  const mails = (messages || []).map(toMail).filter(m => m.numbers.has(n));
  return { emails: mails.length, system: SUMMARY_SYSTEM, prompt: mails.length ? `${transcript(n, mails)}\n\nSummarize this change request.` : '' };
}

export function comment({ number, text, emails, by, truncated = false, at = new Date() }) {
  const clean = String(text || '').trim();
  if (!clean) throw new Error('empty summary');
  const meta = { provider: HANDOFF_PROVIDER, model: HANDOFF_MODEL, emails: Number(emails) || 0, by: String(by || '') };
  return `### Summary of ${meta.emails} email(s)\n\n${mdSafe(clean, 20000)}\n\n_Generated by Claude Code for ${inline(meta.by)} at ${pt(at)} (r360 has no AI provider key yet, so the summary watcher made it)${truncated ? '. The mailbox scan hit its limit, so the oldest emails may be missing' : ''}._\n\n${summaryBlock(meta)}`;
}

export const noMailComment = number => `### Summary not made\n\nNo emails with ${changeNumber(number)} were found in the change mailbox, so there is nothing to summarize yet.`;

async function main(mode) {
  let raw = '';
  for await (const chunk of process.stdin) raw += chunk;
  const input = JSON.parse(raw || '{}');
  const out = mode === 'prompt' ? prepare(input) : mode === 'comment' ? { body: comment(input) } : mode === 'nomail' ? { body: noMailComment(input.number) } : null;
  if (!out) throw new Error('usage: node tools/summarize-change.mjs prompt|comment|nomail < input.json');
  process.stdout.write(JSON.stringify(out));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main(process.argv[2]).catch(e => { process.stderr.write(`${e.message}\n`); process.exit(1); });
}
